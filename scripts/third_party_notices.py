#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md for the code linked into release binaries.

Release pipeline file. Modules come from `go list -deps` for every release target
with CGO_ENABLED=0, so test-only and other-platform dependencies are excluded.
Every module must provide a license file at its root; NOTICE and PATENTS files
are copied as well. The Go standard library license is included because it is
linked into every binary. Uses only Python's standard library.
"""

import argparse
import os
from pathlib import Path
import re
import subprocess
import sys

TARGETS = [("darwin", "amd64"), ("darwin", "arm64"), ("linux", "amd64"), ("linux", "arm64")]
MAIN_PACKAGE = "./cmd/projectory"
NOTICE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|PATENTS)([-._].*)?$", re.IGNORECASE)
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING)", re.IGNORECASE)
MODULE_FORMAT = (
    "{{with .Module}}{{if not .Main}}"
    "{{with .Replace}}{{.Path}}\t{{.Version}}\t{{.Dir}}"
    "{{else}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}"
    "{{end}}{{end}}"
)


def go(args, goos=None, goarch=None):
    env = {**os.environ, "CGO_ENABLED": "0", "GOFLAGS": "-mod=readonly"}
    if goos:
        env.update(GOOS=goos, GOARCH=goarch)
    return subprocess.run(["go", *args], env=env, check=True, capture_output=True, text=True).stdout


def shipped_modules():
    modules = {}
    for goos, goarch in TARGETS:
        for line in go(["list", "-deps", "-f", MODULE_FORMAT, MAIN_PACKAGE], goos, goarch).splitlines():
            if not line:
                continue
            path, version, directory = line.split("\t")
            if not directory:
                raise SystemExit(f"module {path} {version} has no local source; run go mod download")
            modules[path] = (version, Path(directory))
    return modules


def notice_files(directory):
    names = sorted((p.name for p in directory.iterdir() if p.is_file() and NOTICE_FILE.match(p.name)), key=str.casefold)
    return names if any(LICENSE_FILE.match(name) for name in names) else []


def read_text(path):
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError as error:
        raise SystemExit(f"{path}: not UTF-8 text ({error})") from error
    return text.replace("\r\n", "\n").rstrip() + "\n"


def fenced(text):
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}text\n{text}{fence}\n"


def render(components):
    out = [
        "# Third-party notices\n",
        "\nProjectory release binaries include the following third-party software. "
        "This file is generated by `scripts/third_party_notices.py` from the Go packages "
        "linked into the darwin/linux amd64/arm64 builds; do not edit it by hand.\n",
        "\n| Component | Version | Files |\n| --- | --- | --- |\n",
    ]
    for name, version, files in components:
        out.append(f"| {name} | {version} | {', '.join(f.name for f in files)} |\n")
    for name, version, files in components:
        out.append(f"\n## {name} {version}\n")
        for path in files:
            out.append(f"\n### {path.name}\n\n")
            out.append(fenced(read_text(path)))
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, required=True, help="Markdown file to write")
    args = parser.parse_args()

    components = []
    goroot = Path(go(["env", "GOROOT"]).strip())
    goversion = go(["env", "GOVERSION"]).strip()
    components.append(("Go standard library", goversion, [goroot / name for name in notice_files(goroot)]))

    missing = []
    for path, (version, directory) in sorted(shipped_modules().items()):
        names = notice_files(directory)
        if not names:
            missing.append(f"{path} {version}")
        components.append((path, version, [directory / name for name in names]))
    if not components[0][2]:
        missing.insert(0, f"Go standard library {goversion}")
    if missing:
        print("No license file found for shipped components:", file=sys.stderr)
        for item in missing:
            print(f"  {item}", file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(components), encoding="utf-8")
    print(f"Wrote {args.output} ({len(components) - 1} modules plus the Go standard library).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
